const dict: Record<Lang, Record<Key, string>> = { en, tr };

export const translate = (lang: Lang, key: Key, vars?: Vars) =>
  dict[lang][key].replace(/\{(\w+)\}/g, (_, k: string) => String(vars?.[k] ?? `{${k}}`));

/** Translate function, carrying its language so callers can lowercase or format numbers correctly. */
export type T = ((key: Key, vars?: Vars) => string) & { lang: Lang };

export const detectLang = (): Lang =>
  typeof navigator !== 'undefined' && navigator.language?.toLowerCase().startsWith('tr') ? 'tr' : 'en';